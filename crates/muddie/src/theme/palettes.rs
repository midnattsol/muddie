//! The themes, each a palette for the interface and the MUD's text, and
//! the other palettes the MUD's text can have.

use super::*;

pub(super) const fn rgb(hex: u32) -> Color32 {
    Color32::from_rgb((hex >> 16) as u8, (hex >> 8) as u8, hex as u8)
}

